        /// Writes the full exception (type, message, stack trace, inner exceptions) inside a
        /// default-collapsed "Exception details" fold. Callers write their own header line first; this
        /// keeps a failure report scannable while leaving the trace one click away when a failure is not
        /// self-explanatory.
        /// </summary>
        public static void WriteExceptionDetails(this ITextOutput output, Exception ex)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "f74e5698-a64e-4ee2-97e8-198bce98abfb" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            ArgumentNullException.ThrowIfNull(output);
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "a1dc2570-cf54-43d4-b57c-c9ab4b1dd93e" + System.Environment.NewLine);
