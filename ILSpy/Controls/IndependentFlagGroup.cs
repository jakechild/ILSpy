                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var next = current switch
            {
                TriState.DontCare => TriState.Required,
                TriState.Required => TriState.Excluded,
                _ => TriState.DontCare,
            };
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
