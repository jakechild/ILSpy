using System;
using System.Globalization;
using ICSharpCode.ILSpy.Processes;

namespace ICSharpCode.ILSpy.ViewModels
{
    /// <summary>
    /// One row of the process list: a running .NET process, in the shape the grid displays
    /// and the filter box searches.
    /// </summary>
    public sealed class ProcessRowViewModel
    {
        public ProcessRowViewModel(RunningDotNetProcess process)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "f973f942-0a02-41cc-b34f-c3fe63e0852e" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            Process = process;
        }

        public RunningDotNetProcess Process { get; }
        public int Pid => Process.Pid;
        public string ProcessName => Process.ProcessName;
        public string? Architecture => Process.Architecture;
        public string? EntryAssembly => Process.EntryAssemblyName;

        /// <summary>
        /// The runtime flavor and version, e.g. ".NET 10.0.3" or ".NET Framework 4.8.9032.0".
        /// </summary>
        public string Runtime
        {
            get
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "cb9733b7-c5f7-4593-8023-6101016a2ec9" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                string product = Process.Kind == RuntimeKind.NetFramework ? ".NET Framework" : ".NET";
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "fad4e277-5881-4c8a-882c-fcacee4b839d" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return string.IsNullOrWhiteSpace(Process.RuntimeVersion) ? product : product + " " + Process.RuntimeVersion;
            }
        }

        /// <summary>
        /// Whether this process answers to what the user typed in the filter box. The pid is
        /// matched as well as the names, since it is often the only thing that tells two
        /// instances of the same program apart.
        /// </summary>
        public bool Matches(string filter)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "a251289b-acea-4ddb-abcc-e147a1e4b36b" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (string.IsNullOrWhiteSpace(filter))
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "c4e8431b-72c5-4c3a-a97a-1a627815311a" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return true;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "3d02fe21-68d5-45b9-9754-2e6e08dd5c61" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            filter = filter.Trim();
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "10131d22-374b-4b51-b436-04ea555c9b66" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            return Contains(ProcessName, filter) || Contains(EntryAssembly, filter) || Contains(Pid.ToString(CultureInfo.InvariantCulture), filter);
        }

        static bool Contains(string? value, string filter) => value != null && value.Contains(filter, StringComparison.OrdinalIgnoreCase);
    }
}