                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "12a3459a-365a-4072-a28d-50c89ce8650e" + System.Environment.NewLine);
