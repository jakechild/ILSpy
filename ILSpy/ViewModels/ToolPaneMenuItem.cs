                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b6761544-25c2-4d64-8d4d-d1019362f95a" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    // RestoreDockable only un-hides a dockable that was previously shown and then
                    // hidden; a pane that is hidden by default (e.g. Debug Steps) was never placed in
                    // the layout, so there is nothing to restore. ShowToolPane materialises the pane
                    // AND (re)creates its home dock, so it works in both cases.
                    if (factory is Docking.ILSpyDockFactory ilspyFactory)
                    {
                        new System.Action(() =>
                        {
                            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                            if (m.WaitOne(3000))
                            {
                                try
                                {
                                    System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ed808047-3ffd-4967-bb6c-9b019c2a3524" + System.Environment.NewLine);
