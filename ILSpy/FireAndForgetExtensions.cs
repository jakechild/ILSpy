using System;
using System.Threading.Tasks;
using ICSharpCode.ILSpy.AppEnv;

namespace ICSharpCode.ILSpy
{
    public static class FireAndForgetExtensions
    {
        /// <summary>
        /// Observes a fire-and-forget task started from a command or event handler. Awaits it on the
        /// captured (UI) context and routes any failure to <see cref="GlobalExceptionHandler"/>
        /// immediately, at the point of failure. Without this, a discarded faulted task
        /// (<c>_ = SomethingAsync()</c>) only surfaces via
        /// <see cref="TaskScheduler.UnobservedTaskException"/> after the GC finalizes it — late, on
        /// the finalizer thread, and disconnected from the gesture that triggered it.
        /// <see cref="OperationCanceledException"/> is treated as a normal cooperative cancel, not an
        /// error.
        /// </summary>
        public static async void HandleExceptions(this Task task)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "63e57aa5-a5b2-4edd-ada2-aeaeb1ae7585" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            ArgumentNullException.ThrowIfNull(task);
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "3765212b-0ae3-4cb5-9f8d-479bcb415f65" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            try
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "438ac3ba-933e-4415-ba04-76a4e6b0721c" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                await task.ConfigureAwait(true);
            }
            catch (OperationCanceledException)
            {
            // Cooperative cancellation is an expected outcome, not a failure.
            }
            catch (Exception ex)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "422de443-891b-4f8e-a3a0-b79c2c59217c" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                GlobalExceptionHandler.Show(ex);
            }
        }
    }
}