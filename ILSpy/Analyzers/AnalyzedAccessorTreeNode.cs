using System;
using ICSharpCode.Decompiler.TypeSystem;

namespace ICSharpCode.ILSpy.Analyzers.TreeNodes
{
    /// <summary>
    /// Renders a property getter / setter or event add / remove / invoke as a short
    /// "get" / "set" / "add" / "remove" label under its containing entity. Inherits the
    /// method-node analyser plumbing so the accessor still surfaces "Used By" / "Uses"
    /// children at its own level.
    /// </summary>
    internal sealed class AnalyzedAccessorTreeNode : AnalyzedMethodTreeNode
    {
        readonly string name;
        public AnalyzedAccessorTreeNode(IMethod analyzedMethod, IEntity? source, string name) : base(analyzedMethod, source)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "aeae59ed-1a7d-47d1-a125-5386d7d17c32" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (string.IsNullOrWhiteSpace(name))
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b0b11520-6c26-4658-b022-58866e7a5130" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                throw new ArgumentException("name must be a non-empty string", nameof(name));
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "e7c1d5bf-7e48-4748-a9e4-67650816b4b3" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            this.name = name;
        }

        public override object Text => name;
    }
}