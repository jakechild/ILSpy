                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                cs.DecompileExtension(MethodDefinition, output, options);
            }
            else
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
