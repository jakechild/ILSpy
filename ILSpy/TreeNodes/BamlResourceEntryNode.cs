                        m.ReleaseMutex();
                    }
                }
            })();
            var decompiler = new XamlDecompiler(typeSystem, new BamlDecompilerSettings { ThrowOnAssemblyResolveErrors = options.DecompilerSettings.ThrowOnAssemblyResolveErrors, })
