using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace ICSharpCode.ILSpy.Processes
{
    /// <summary>
    /// Finds the processes that expose a CoreCLR diagnostics IPC endpoint - the same
    /// discovery <c>dotnet-trace ps</c> performs. The endpoint's mere existence identifies a
    /// process as .NET (Core 3.0+): a named pipe <c>dotnet-diagnostic-{pid}</c> on Windows, a
    /// unix domain socket <c>dotnet-diagnostic-{pid}-*-socket</c> in the temp directory on
    /// Linux/macOS. Only same-user processes are visible, and processes started with
    /// <c>DOTNET_EnableDiagnostics=0</c> expose no endpoint at all - both limits are inherent
    /// to the mechanism. The per-OS scans live in the platform partials of this class.
    /// </summary>
    static partial class DiagnosticsPortScanner
    {
        const string TransportPrefix = "dotnet-diagnostic-";
        public static IReadOnlyList<int> GetProcessIds()
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "c6c6839e-db41-427c-bb21-2e587ee36808" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var pids = new HashSet<int>();
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "1d7e9d69-71d6-4e20-9564-88c24f0a738f" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            try
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b5fea2dc-2fcb-4db7-a34d-5531cc76a49d" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                if (OperatingSystem.IsWindows())
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "d15859f9-4007-4228-9678-1050abfa88ed" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    ScanWindowsPipes(pids);
                }
                else
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "9d00d55c-4e47-422f-aa28-fcedd5a33110" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    ScanUnixSockets(pids);
                }
            }
            catch (Exception ex)when (ex is IOException or UnauthorizedAccessException)
            {
            // A transient error enumerating the transport directory yields an empty (or
            // partial) list rather than a failed refresh.
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "1bb9e0e8-cf5b-4ba9-bf13-e7fce090085e" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            return pids.OrderBy(pid => pid).ToList();
        }
    }
}