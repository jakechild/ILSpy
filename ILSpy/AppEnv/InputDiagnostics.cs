                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                while (ring.Count > RingCapacity)
                    ring.Dequeue();
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
