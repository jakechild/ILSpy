using System;
using System.Collections.Generic;
using ICSharpCode.Decompiler;

namespace ICSharpCode.ILSpy.AppEnv
{
    /// <summary>A single non-fatal composition failure: which part failed, and why.</summary>
    public sealed record CompositionError(string Source, Exception Exception);
    /// <summary>
    /// Collects non-fatal MEF composition failures -- a plugin assembly that fails to load, or an
    /// exported command whose constructor throws when the menu/toolbar builder materialises it.
    /// Unlike <see cref="StartupExceptions"/> (fatal startup errors that replace the app with an
    /// error window), these are recoverable: the offending part is skipped, the app keeps running,
    /// and the collected errors are surfaced to the user in a document tab (see <see cref="WriteTo"/>)
    /// and, when <see cref="AppLog.Category.Composition"/> is enabled, written to the log file.
    /// </summary>
    public static class CompositionErrors
    {
        static readonly List<CompositionError> items = new();
        public static IReadOnlyList<CompositionError> Items => items;
        public static bool Any => items.Count > 0;

        /// <summary>Records a composition failure and logs it under the Composition category.</summary>
        public static void Report(string source, Exception exception)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b19912c0-ee10-474e-a564-2cbca4399c6d" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            items.Add(new CompositionError(source, exception));
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ffa7dcb7-ea25-40e2-a7da-958925f13b4e" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            AppLog.Write(AppLog.Category.Composition, $"{source}: {exception}");
        }

        /// <summary>Clears the collected errors. Intended for test isolation.</summary>
        public static void Clear() => items.Clear();
        /// <summary>Renders every collected error into <paramref name="output"/> for display.</summary>
        public static void WriteTo(ITextOutput output)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "3a285e0c-9644-42cc-a4d1-825eb1cf1048" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            ArgumentNullException.ThrowIfNull(output);
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "3b95b977-e0e8-4d09-862c-ce0a94d703ec" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            foreach (var error in items)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "df19b82c-240c-41e2-bf5f-6775fa6381c8" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                output.WriteLine($"[{error.Source}]");
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "831c941c-0ba4-47e7-ae1a-a1b9c874ac51" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                output.WriteLine(error.Exception.ToString());
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8e258b8c-d583-43ad-abfa-e2765853afce" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                output.WriteLine();
            }
        }
    }
}