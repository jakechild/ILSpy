    sealed class AssertionFailedException : Exception
    {
        readonly string trimmedStack;
        public AssertionFailedException(string message, string? detailMessage, string trimmedStack) : base(string.IsNullOrEmpty(detailMessage) ? message : message + Environment.NewLine + detailMessage)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b8746f47-fbfc-4461-94cc-481332a1d011" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            this.trimmedStack = trimmedStack;
        }

        // The dialog renders exception.ToString() in its details box; override so the stack
        // it sees is the assert site, not the ILSpyTraceListener itself.
        public override string ToString() => GetType().FullName + ": " + Message + Environment.NewLine + trimmedStack;
        public override string? StackTrace => trimmedStack;
    }
