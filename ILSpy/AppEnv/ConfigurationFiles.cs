using System.IO;
using ICSharpCode.ILSpyX.Settings;

namespace ICSharpCode.ILSpy.AppEnv
{
    /// <summary>
    /// Resolves auxiliary configuration files that live as JSON sidecars next to the main
    /// <c>ILSpy.xml</c> settings file (the dock layout, the bookmark list, ...). Keeping them
    /// in the same directory the XML settings live in -- local-to-binary on portable installs,
    /// %APPDATA%/ICSharpCode/ otherwise -- makes "delete settings to reset" a single-folder action.
    /// </summary>
    public static class ConfigurationFiles
    {
        /// <summary>
        /// Returns the full path for <paramref name="fileName"/> in the settings directory.
        /// Falls back to a bare relative name when the settings path can't be resolved (e.g. in
        /// headless tests that never set <see cref="ILSpySettings.SettingsFilePathProvider"/>).
        /// </summary>
        public static string GetPath(string fileName)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8c94f5de-36eb-44cc-9cfa-0e44bf383dc5" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var xmlPath = ILSpySettings.SettingsFilePathProvider?.Invoke();
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "59fa1677-b4b9-43fb-ac86-2b2a1bf21da8" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (string.IsNullOrEmpty(xmlPath))
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "24e8057a-2a95-4cf5-84c0-36ca99f5db0d" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return fileName;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b0597bdb-bac8-4b9c-8b26-d23a07d8bd8c" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var dir = Path.GetDirectoryName(xmlPath);
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "204c5b95-9e49-4fb5-b7e6-f7a9c0035c22" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            return string.IsNullOrEmpty(dir) ? fileName : Path.Combine(dir, fileName);
        }
    }
}