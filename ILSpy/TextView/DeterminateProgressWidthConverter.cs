using System;
using System.Collections.Generic;
using System.Globalization;
using Avalonia.Data.Converters;

namespace ICSharpCode.ILSpy.TextView
{
    /// <summary>
    /// Width for the determinate progress bar in the decompile/operation overlay: a fixed fraction
    /// (75%) of the overlay width, so the bar is a stable size instead of shrinking and growing with
    /// the status text underneath it. While the bar is indeterminate it returns <c>NaN</c> (auto),
    /// leaving that mode's natural sizing untouched.
    /// </summary>
    public sealed class DeterminateProgressWidthConverter : IMultiValueConverter
    {
        public static readonly DeterminateProgressWidthConverter Instance = new();
        const double Fraction = 0.75;
        public object Convert(IList<object?> values, Type targetType, object? parameter, CultureInfo culture)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ae2fdd4a-8ce1-406b-95ca-6a896a9a15f0" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (values.Count == 2 && values[0] is double overlayWidth && values[1] is bool isIndeterminate && !isIndeterminate && overlayWidth > 0)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8bb96b1a-0ec2-4dae-a698-02b4c8b95613" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return overlayWidth * Fraction;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "5401946c-8bd7-4c99-b7fe-480d8c31aa5b" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            return double.NaN;
        }
    }
}