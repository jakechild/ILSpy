        // Avalonia configuration, don't remove; also used by visual designer.
        public static AppBuilder BuildAvaloniaApp()
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ddcc613f-6a32-4036-b877-b52160239d0e" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var builder = AppBuilder.Configure<App>().UsePlatformDetect()// Render popups (menus, flyouts, tooltips) in the window's own overlay layer instead of
            // separate native child windows. On X11/XWayland native popups can lose focus and
            // self-dismiss within ~100ms of opening (observed on the document-strip overflow
            // dropdown: it opened and closed before becoming visible).
            .With(new X11PlatformOptions { OverlayPopups = true });
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "859cefdf-e07f-4ecb-86cc-7a89c66c02a8" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
#if DEBUG
			// Enables and attaches the Avalonia 12 DevTools bridge (it calls AttachDeveloperTools
			// internally, so no separate App-level attach is needed -- a second call throws
			// "already attached"). The avdt global tool connects over this bridge. Gated on DEBUG
			// because the DiagnosticsSupport assets are excluded from Release.
			builder = builder.WithDeveloperTools();
#endif
            return builder.LogToTrace();
        }
