                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ffdff4c6-8311-46d5-9b55-750df6bb9ef9" + System.Environment.NewLine);
