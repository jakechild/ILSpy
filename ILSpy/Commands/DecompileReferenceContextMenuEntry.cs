using System.Composition;
using ICSharpCode.Decompiler.TypeSystem;
using ICSharpCode.ILSpy.Properties;

namespace ICSharpCode.ILSpy.Commands
{
    /// <summary>
    /// Right-click → "Decompile" (go to definition) on a symbol in the decompiled code. Navigates
    /// the assembly tree to the clicked entity's definition and decompiles it -- the menu equivalent
    /// of clicking the hyperlink. Visible only when the click landed on a reference that resolves to
    /// an <see cref="IEntity"/>.
    /// </summary>
    [ExportContextMenuEntry(Header = nameof(Resources.Decompile), Category = "Navigation", Order = 150)]
    [Shared]
    public sealed class DecompileReferenceContextMenuEntry : IContextMenuEntry
    {
        public bool IsVisible(TextViewContext context) => context.Reference?.Reference is IEntity;
        public bool IsEnabled(TextViewContext context) => true;
        public void Execute(TextViewContext context)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "454a3d3e-10bf-456d-bff4-048cf86d83ec" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (context.Reference?.Reference is not IEntity entity)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "d38cba67-52d7-4f32-962b-abdc201b4445" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "1c35bc5b-9826-4a31-8977-7663baf40365" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            Util.MessageBus.Send(this, new Util.NavigateToReferenceEventArgs(entity));
        }
    }
}