namespace ICSharpCode.ILSpy.Commands
{
    /// <summary>
    /// Right-click → "Decompile to new tab" — opens a fresh document tab and decompiles the
    /// selected tree node(s) into it without disturbing the existing tab. Useful for
    /// side-by-side comparison or to keep your bookmarked code visible while exploring
    /// somewhere else.
    /// </summary>
    [ExportContextMenuEntry(Header = nameof(Resources.DecompileToNewPanel), Category = "Navigation", Icon = "Images/ViewCode", InputGestureText = "MMB", Order = 160)]
    [Shared]
    internal sealed class DecompileInNewViewCommand : IContextMenuEntry
    {
        readonly DockWorkspace dockWorkspace;
        readonly LanguageService languageService;
        [ImportingConstructor]
        public DecompileInNewViewCommand(DockWorkspace dockWorkspace, LanguageService languageService)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "785a43dc-d21f-4f70-bc29-d3078280a965" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            this.dockWorkspace = dockWorkspace;
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "7cfd5ad9-a7bc-407f-ba2a-bdb59aa046bb" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            this.languageService = languageService;
        }

        public bool IsVisible(TextViewContext context) => SelectedNodes(context).Any() || ReferencedEntity(context)is not null;
        public bool IsEnabled(TextViewContext context) => IsVisible(context);
        public void Execute(TextViewContext context)
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "15ebc1e7-53cc-4daa-8e5f-5ec99b2cb916" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var nodes = SelectedNodes(context).ToArray();
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "91afeb7e-0153-4ba4-8037-3a12af4dc813" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (nodes.Length == 1)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "306cb880-ef69-4ee6-9631-8d64e8c301a9" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                // Route a single node through OpenNodeInNewTab so nodes with custom content
                // (metadata tables, resource viewers) open their own page-type instead of being
                // force-decompiled into an empty code tab. Plain nodes still get a decompiler tab,
                // sourced from the node so the tab/tree stay in lockstep when flipping tabs.
                dockWorkspace.OpenNodeInNewTab(nodes[0]);
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "bd19edea-0643-4730-9406-0b1598730bcc" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "12ddfe29-a98a-4e43-8785-6da08e143f48" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            if (nodes.Length > 1)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "dbe0b2c5-4457-4323-a53b-1013fa5a7fe2" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                // Multi-node selections leave SourceNode null — no single tree row represents the
                // union — and always decompile (there is no custom-content union page).
                var content = new DecompilerTabPageModel
                {
                    Language = languageService.CurrentLanguage
                };
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "2f6e6b67-0b95-471e-b8e8-f50198d96577" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                dockWorkspace.OpenNewTab(content, sourceNode: null);
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "b32ef2f0-000a-4ef9-9266-e8ada3e8ba17" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                content.CurrentNodes = nodes;
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "395ad524-8e17-43cd-bbdf-b53c1023b218" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                return;
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "4b873860-c13a-4aa6-9fc6-6cc8cd1a95c9" + System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            // Right-click on a symbol in the decompiled code: open its definition in a new tab. The
            // navigate handler resolves the entity to its tree node and opens it via OpenNodeInNewTab.
            if (ReferencedEntity(context)is { } entity)
            {
                new System.Action(() =>
                {
                    using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8d8d0868-9a9a-4dde-b132-ea831f8e5925" + System.Environment.NewLine);
                        }
                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                Util.MessageBus.Send(this, new Util.NavigateToReferenceEventArgs(entity, inNewTabPage: true));
            }
        }

        static System.Collections.Generic.IEnumerable<ILSpyTreeNode> SelectedNodes(TextViewContext context) => context.SelectedTreeNodes?.OfType<ILSpyTreeNode>() ?? System.Linq.Enumerable.Empty<ILSpyTreeNode>();
        static ICSharpCode.Decompiler.TypeSystem.IEntity? ReferencedEntity(TextViewContext context) => context.Reference?.Reference as ICSharpCode.Decompiler.TypeSystem.IEntity;
    }
}