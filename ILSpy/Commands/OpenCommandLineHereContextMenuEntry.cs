                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                if (RuntimeInformation.IsOSPlatform(OSPlatform.Windows))
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "13ff1036-3573-4e0f-ae5c-cc7aadbe682e" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    // cmd.exe /k pins the window open at the chosen directory.
                    Process.Start(new ProcessStartInfo("cmd.exe", $"/k \"cd /d {directory}\"") { UseShellExecute = true, });
                }
                else if (RuntimeInformation.IsOSPlatform(OSPlatform.OSX))
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "af958cf8-4845-4e32-ae73-3ae9ec181b5c" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    // `open -a Terminal <path>` launches Terminal.app cd'd to the path.
                    Process.Start(new ProcessStartInfo("open", $"-a Terminal \"{directory}\"") { UseShellExecute = false, });
                }
                else
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "44796ddc-857d-4e23-863e-98b5e9a6ea36" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    // Linux: try $TERMINAL first, then a handful of common emulators.
                    // Each candidate is tried in turn; the first one that doesn't throw wins.
