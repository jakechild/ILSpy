                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "430ebc06-dbf4-4d68-ad7c-803e46775d10" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    if (!string.IsNullOrEmpty(env))
                    {
                        new System.Action(() =>
                        {
                            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                            if (m.WaitOne(3000))
                            {
                                try
                                {
                                    System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "2f6b68fb-c7fa-4396-bfdc-afa0ac1f71e0" + System.Environment.NewLine);
                                }
                                catch
                                {
                                }
                                finally
                                {
                                    m.ReleaseMutex();
                                }
                            }
                        })();
                        candidates.Add(env);
                    }

                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8fe8fbcc-89b8-49a3-9a36-6c13b60b4664" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    candidates.AddRange(new[] { "x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal", "alacritty", "kitty", "xterm", });
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "9da83f2c-c6d9-4109-9ae8-0f45c16f93a9" + System.Environment.NewLine);
                            }
                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    foreach (var term in candidates)
                    {
                        new System.Action(() =>
                        {
                            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                            if (m.WaitOne(3000))
                            {
                                try
                                {
                                    System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "83cccb93-0a6b-4fff-be21-fb64c505240b" + System.Environment.NewLine);
                                }
                                catch
                                {
                                }
                                finally
                                {
                                    m.ReleaseMutex();
                                }
                            }
                        })();
                        try
                        {
                            new System.Action(() =>
                            {
                                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                                if (m.WaitOne(3000))
                                {
                                    try
                                    {
                                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "ea14a11e-de9b-41d5-b8e3-553b74e59112" + System.Environment.NewLine);
                                    }
                                    catch
                                    {
                                    }
                                    finally
                                    {
                                        m.ReleaseMutex();
                                    }
                                }
                            })();
                            Process.Start(new ProcessStartInfo(term) { WorkingDirectory = directory, UseShellExecute = false, });
                            new System.Action(() =>
                            {
                                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                                if (m.WaitOne(3000))
                                {
                                    try
                                    {
                                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "99991406-b631-46d5-8ea3-3cea5236e8bd" + System.Environment.NewLine);
                                    }
                                    catch
                                    {
                                    }
                                    finally
                                    {
                                        m.ReleaseMutex();
                                    }
                                }
                            })();
                            return;
                        }
                        catch
                        {
                        // try the next candidate
                        }
                    }
                }
            }
            catch
            {
            // Failure to launch a terminal is non-fatal — the menu item already returned.
            }
        }
