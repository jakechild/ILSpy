        {
            public static BookmarkRecord From(Bookmark b) => new(b.Name, b.Enabled, b.FileName, b.AssemblyFullName, b.ModuleName, b.Token, b.Kind, b.ILOffset, b.LineNumber, b.MemberName, b.LocationNodeName, b.ViewState);
            public Bookmark ToBookmark() => new()
            {
                Name = Name,
                Enabled = Enabled,
