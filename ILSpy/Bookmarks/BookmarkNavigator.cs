                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "521a4415-d244-480b-a55c-dfeb4e1c9b6e" + System.Environment.NewLine);
