                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                if (files.Count > 0)
                {
                    new System.Action(() =>
                    {
                        using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                        if (m.WaitOne(3000))
                        {
                            try
                            {
                                System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "14099984-4dc8-4b9f-a774-13d8c2622c97" + System.Environment.NewLine);
