                            catch
                            {
                            }
                            finally
                            {
                                m.ReleaseMutex();
                            }
                        }
                    })();
                    OpenFolder(folder);
                }
            }
            catch
            {
            // Best-effort: the user can navigate manually if even this fails.
            }
