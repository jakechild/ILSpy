                    if (m.WaitOne(3000))
                    {
                        try
                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8948e1f5-1c44-4e92-a74a-ebd7f37145ac" + System.Environment.NewLine);
                        }
                        catch
