                        {
                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "5d693261-ae30-4bca-9bfb-9e3737765a90" + System.Environment.NewLine);
