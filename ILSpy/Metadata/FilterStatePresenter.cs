                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "9231ffba-d43a-46a8-b830-6362ebb86fbe" + System.Environment.NewLine);
