                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "d4c6cf36-33a1-463c-b9b0-a7dd412fbfd6" + System.Environment.NewLine);
                    }
