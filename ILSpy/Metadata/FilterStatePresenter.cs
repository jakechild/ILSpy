                            System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "8304cb1c-cc26-4091-a486-2b33ec2548ee" + System.Environment.NewLine);
