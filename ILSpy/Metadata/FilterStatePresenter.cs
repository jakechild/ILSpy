                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "e408076c-3e13-44e2-9514-51bea3d8e8f3" + System.Environment.NewLine);
                    }
