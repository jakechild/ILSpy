                {
                    try
                    {
                        System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "4a4c4439-8ea5-4b9d-b598-3b75727431b6" + System.Environment.NewLine);
                    }
                    catch
