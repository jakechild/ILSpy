                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            var requiredFlags = state.Schema.IndependentFlags.Where(f => state.FlagStates.TryGetValue(f.Name, out var t) && t == TriState.Required).Select(f => f.Name).ToList();
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
