                        catch
                        {
                        }
                        finally
                        {
                            m.ReleaseMutex();
                        }
                    }
                })();
                clauses.Add(labels.Count == 1 ? $"{group.Name} = {labels[0]}" : $"{group.Name} ∈ {{{string.Join(", ", labels)}}}");
            }

            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
